double TemplateModel::CalcDistance(std::vector<RawCoordinates>& points, int index_begin, int index_end) {
    const int n = (int)points.size();
    if (points.size() < 2 || (index_end != -1 && index_end - index_begin < 2) || n - index_begin < 2) return 0.0;

    //endIndex = -1 ==>Ĭ�ϵ�ĩβ
    if (index_end == -1)index_end = n;

    double sum = 0.0;
    for (int i = index_begin + 1; i < index_end; ++i) {
        sum += distanceMeters(points[i - 1].latitude, points[i - 1].lontitude, points[i].latitude, points[i].lontitude);
    }
    return (sum/1000);
};

